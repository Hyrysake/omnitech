def _is_empty(db, table):
    """Повертає True, якщо в таблиці немає жодного рядка.

    Назву таблиці не можна передати як параметр «?», тому вона вставляється в текст запиту.
    Це безпечно, бо сюди потрапляють лише назви, написані нами нижче в цьому файлі.
    """
    return db.execute(f'SELECT COUNT(*) FROM {table}').fetchone()[0] == 0


def seed_database(db):
    """Заповнює порожні таблиці демонстраційними даними."""
    if _is_empty(db, 'categories'):
        db.executemany('INSERT INTO categories (name) VALUES (?)', [(name,) for name in CATEGORIES])

    if _is_empty(db, 'products'):
        # Словник «назва категорії -> її id», щоб у товарі вказати category_id
        category_ids = {row['name']: row['id'] for row in db.execute('SELECT id, name FROM categories')}
        db.executemany(
            'INSERT INTO products (category_id, name, description, price, image, is_featured) '
            'VALUES (?, ?, ?, ?, ?, ?)',
            [(category_ids[category], name, description, price,
              f'https://picsum.photos/id/{photo_id}/600/400', featured)
             for name, category, description, price, photo_id, featured in PRODUCTS],
        )

    if _is_empty(db, 'users'):
        db.executemany(
            'INSERT INTO users (name, email, password_hash, role) VALUES (?, ?, ?, ?)',
            # generate_password_hash перетворює пароль на «хеш»: за ним пароль не відновити
            [(name, email, generate_password_hash(password), role) for name, email, password, role in USERS],
        )

    if _is_empty(db, 'feedback'):
        db.executemany(
            'INSERT INTO feedback (name, email, message, is_read, created_at) VALUES (?, ?, ?, ?, ?)',
            FEEDBACK,
        )

    if _is_empty(db, 'orders'):
        _seed_orders(db)

    if _is_empty(db, 'reviews'):
        _seed_reviews(db)


def _seed_orders(db):
    """Додає демонстраційні замовлення разом з їхніми рядками."""
    products = {row['name']: row for row in db.execute('SELECT id, name, price FROM products')}
    user_ids = {row['email']: row['id'] for row in db.execute('SELECT id, email FROM users')}
    for user_email, name, phone, email, address, status, created_at, lines in ORDERS:
        total = sum(products[product_name]['price'] * quantity for product_name, quantity in lines)
        cursor = db.execute(
            'INSERT INTO orders (user_id, customer_name, phone, email, address, total, status, created_at) '
            'VALUES (?, ?, ?, ?, ?, ?, ?, ?)',
            (user_ids.get(user_email), name, phone, email, address, total, status, created_at),
        )
        order_id = cursor.lastrowid          # номер щойно створеного замовлення
        db.executemany(
            'INSERT INTO order_items (order_id, product_id, quantity, price) VALUES (?, ?, ?, ?)',
            [(order_id, products[product_name]['id'], quantity, products[product_name]['price'])
             for product_name, quantity in lines],
        )


def _seed_reviews(db):
    """Додає демонстраційні відгуки. Ті, що написав демо-клієнт, прив'язуються до його акаунта."""
    product_ids = {row['name']: row['id'] for row in db.execute('SELECT id, name FROM products')}
    user_ids = {row['email']: row['id'] for row in db.execute('SELECT id, email FROM users')}
    db.executemany(
        'INSERT INTO reviews (product_id, user_id, author_name, rating, text, created_at) '
        'VALUES (?, ?, ?, ?, ?, ?)',
        [(product_ids[product], user_ids.get(email), author, rating, text, created_at)
         for product, email, author, rating, text, created_at in REVIEWS],
    )
