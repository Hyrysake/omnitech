def _is_empty(db, table):
    """Повертає True, якщо в таблиці немає жодного рядка.

    Назву таблиці не можна передати як параметр «?», тому вона вставляється в текст запиту.
    Це безпечно, бо сюди потрапляють лише назви, написані нами нижче в цьому файлі.
    """
    return db.execute(f'SELECT COUNT(*) FROM {table}').fetchone()[0] == 0


def seed_database(db):
    """Заповнює порожні таблиці демонстраційними даними."""
    if _is_empty(db, 'categories'):
        db.executemany('INSERT INTO categories (name) VALUES (?)', [(name,) for name in CATEGORIES])

    if _is_empty(db, 'products'):
        # Словник «назва категорії -> її id», щоб у товарі вказати category_id
        category_ids = {row['name']: row['id'] for row in db.execute('SELECT id, name FROM categories')}
        db.executemany(
            'INSERT INTO products (category_id, name, description, price, image, is_featured) '
            'VALUES (?, ?, ?, ?, ?, ?)',
            [(category_ids[category], name, description, price,
              f'https://picsum.photos/id/{photo_id}/600/400', featured)
             for name, category, description, price, photo_id, featured in PRODUCTS],
        )

    if _is_empty(db, 'users'):
        db.executemany(
            'INSERT INTO users (name, email, password_hash, role) VALUES (?, ?, ?, ?)',
            # generate_password_hash перетворює пароль на «хеш»: за ним пароль не відновити
            [(name, email, generate_password_hash(password), role) for name, email, password, role in USERS],
        )
