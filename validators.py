"""Спільні перевірки й перетворення введених даних: їх використовують різні частини сайту."""


def to_int(value):
    """Перетворює рядок із форми чи адреси на ціле число; порожнє або некоректне дає None."""
    try:
        return int(value)
    except (TypeError, ValueError):
        return None
