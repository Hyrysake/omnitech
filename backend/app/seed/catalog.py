def seed_catalog(db: Session) -> None:
    if db.scalar(select(Category.id).limit(1)) is not None:
        return      # каталог уже заповнено
    categories = {name: Category(name=name) for name in CATEGORIES}
    db.add_all(categories.values())

    products = {}
    for name, category, description, price, photo_id, featured in PRODUCTS:
        products[name] = Product(
            category=categories[category], name=name, description=description, price=price,
            image_url=f'https://picsum.photos/id/{photo_id}/600/400', is_featured=bool(featured),
        )
    db.add_all(products.values())
    db.flush()      # отримати id товарів

    user_ids = dict(db.execute(select(User.email, User.id)).all())
    db.add_all(
        Review(product_id=products[product].id, user_id=user_ids.get(email), author_name=author,
               rating=rating, text=text, created_at=datetime.fromisoformat(created_at))
        for product, email, author, rating, text, created_at in REVIEWS
    )
    db.flush()
